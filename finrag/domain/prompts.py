# ── P1 검색어 추출 ─────────────────────────────────────────────────────
class QueryPlan(BaseModel):
    queries: list[str] = Field(description="한국어 위키백과 검색어. 짧은 명사구.")


P1_SYSTEM = """너는 증권사 기업분석 리서치 애널리스트다.
사용자가 특정 상장기업에 대해 질문하면, 답에 필요한 배경 지식을 한국어 위키백과에서 찾기 위한 검색어를 고른다.

규칙
- 검색어는 위키백과 문서 제목 그대로 쓸 수 있는 1~3단어 명사로 쓴다. (좋은 예: "물적분할", "LG화학", "고대역폭 메모리")
- 문장형·조합형 검색어는 쓰지 않는다. (나쁜 예: "LG에너지솔루션 분할 방식", "설립 2020년 12월")
- 선택한 기업 이름은 검색어에 넣지 않는다. 기업 자체 문서는 시스템이 따로 넣는다.
- 질문에 나온 다른 회사, 제품·기술, 사건, 경제·회계 용어를 우선 고른다.
- 최대 {max_queries}개. 관련 없는 일반 단어(주가, 투자, 전망)는 넣지 않는다."""

P1_HUMAN = "[기업]\n{item_text}\n\n[질문]\n{question}"


# ── P2 후보 선별 ───────────────────────────────────────────────────────
class Selection(BaseModel):
    selected: list[int] = Field(description="색인할 후보 번호")
    reason: str = Field(description="고른 기준 한두 문장")


P2_SYSTEM = """너는 기업 리서치 자료 큐레이터다.
위키백과 검색 후보의 제목과 요약만 보고, 질문에 답하는 데 실제로 도움이 될 문서만 고른다.

규칙
- 질문에 직접 나온 회사·개념의 문서는 고른다. (예: 질문에 "LG화학"이 나오면 LG화학 문서)
- 질문의 핵심 개념을 설명하는 일반 문서(예: 물적분할, 고대역폭 메모리)는 고른다.
- 질문과 상관없는 다른 회사, 이름만 같은 문서, 인물, 동음이의어 문서는 고르지 않는다.
- 요약만으로 관련성을 알 수 없으면 제목이 질문과 직접 맞닿을 때만 고른다.
- 최대 {max_select}개."""

P2_HUMAN = "[기업] {company}\n[질문] {question}\n\n[후보]\n{candidates}"


# ── P3 답변 생성 ───────────────────────────────────────────────────────
